#pragma once

#include "sdkconfig.h"

#ifndef LIGHTGW_STAGE
#define LIGHTGW_STAGE 4
#endif
#ifndef LIGHTGW_VARIANT_BUILD
#define LIGHTGW_VARIANT_BUILD 0
#endif

#if LIGHTGW_STAGE < 1 || LIGHTGW_STAGE > 5
#error "LIGHTGW_STAGE must be 1..5"
#endif

#define LIGHTGW_HAS_ZIGBEE       (LIGHTGW_STAGE >= 2)
#define LIGHTGW_HAS_DISCOVERY    (LIGHTGW_STAGE >= 3)
#define LIGHTGW_HAS_CONTROL      (LIGHTGW_STAGE >= 4)
#define LIGHTGW_HAS_SCHEDULER    (LIGHTGW_STAGE >= 4)
#define LIGHTGW_HAS_IR           (LIGHTGW_STAGE >= 5)
#define LIGHTGW_HAS_RTC          1

#define LIGHTGW_HAS_BH1750_EXTENSION    CONFIG_LIGHTGW_BH1750_EXTENSION
#define LIGHTGW_HAS_SHT31_EXTENSION     CONFIG_LIGHTGW_SHT31_EXTENSION
#define LIGHTGW_HAS_SENSOR_EXTENSION    (LIGHTGW_HAS_BH1750_EXTENSION || LIGHTGW_HAS_SHT31_EXTENSION)
#define LIGHTGW_HAS_RAINMAKER_EXTENSION CONFIG_LIGHTGW_RAINMAKER_EXTENSION
#define LIGHTGW_HAS_EXTENSIONS          (LIGHTGW_HAS_SENSOR_EXTENSION || LIGHTGW_HAS_RAINMAKER_EXTENSION)

#if LIGHTGW_VARIANT_BUILD
#if CONFIG_LIGHTGW_VARIANT_FULL
#define LIGHTGW_VARIANT_NAME "FULL"
#elif CONFIG_LIGHTGW_VARIANT_CORE_SENSOR
#define LIGHTGW_VARIANT_NAME "CORE_SENSOR"
#elif CONFIG_LIGHTGW_VARIANT_CORE_CLOUD
#define LIGHTGW_VARIANT_NAME "CORE_CLOUD"
#else
#define LIGHTGW_VARIANT_NAME "CORE"
#endif
#else
#define LIGHTGW_VARIANT_NAME "STAGE"
#endif

#define LIGHTGW_STRINGIFY_INNER(x) #x
#define LIGHTGW_STRINGIFY(x) LIGHTGW_STRINGIFY_INNER(x)
#if LIGHTGW_VARIANT_BUILD
#define LIGHTGW_VERSION "0.10.0-" LIGHTGW_VARIANT_NAME
#else
#define LIGHTGW_VERSION "0.10.0-stage" LIGHTGW_STRINGIFY(LIGHTGW_STAGE)
#endif
